import assert from 'node:assert/strict';
import {starterBook} from '../src/library-catalog.mjs';

const siyer=starterBook('peygamberimiz-muhammed');
assert.ok(siyer,'selected level-three siyer target must exist');
assert.equal(siyer.stage,'level-3');
assert.equal(siyer.availability,'source-verified');
assert.equal(Boolean(siyer.asset),false,'pending siyer must stay unreadable until a reusable historical scan is approved');
assert.equal(siyer.sourceGate?.status,'waiting-reusable-historical-scan');
assert.deepEqual(siyer.sourceGate?.acceptedEditionYears,[1934]);
assert.deepEqual(siyer.sourceGate?.conditionallyAcceptedEditionYears,[1955]);
assert.equal(siyer.sourceGate?.editionComparisonRequired,true);
assert.match(siyer.sourceGate?.conditionalEditionPolicy||'',/1955 Diyanet|1934/i);
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.publicationNo==='40'&&x.conditional===true));
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.recordId==='423781'&&x.callNumber==='A.IV/9738'&&x.conditional===true));
assert.equal(siyer.sourceGate?.preferredScript,'latin');
assert.match(siyer.sourceGate?.selectionReason||'',/Latin harfli|Latin/i);
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.institution==='Uludağ Üniversitesi İlahiyat Fakültesi Kütüphanesi'&&x.callNumber==='297.92 AKS.P'&&x.inventory==='09768'));
assert.ok(siyer.sourceGate?.contentQualityGate?.approvalRequiredBeforeReady===true);
assert.equal(siyer.sourceGate?.contentQualityGate?.status,'review-required');
assert.ok(siyer.sourceGate?.contentQualityGate?.knownConcerns?.some(x=>x.type==='historical-claim'));
assert.match(siyer.sourceGate?.contentQualityGate?.decisionRule||'',/READY yapılmaz/);
assert.ok(siyer.sourceGate?.fallbackCandidates?.some(x=>x.id==='asri-saadet-siyret'&&x.editionYears?.includes(1928)&&/ciddi tahlil|ilmî/i.test(x.contentEvidence||'')));
assert.ok(siyer.sourceGate?.fallbackCandidates?.some(x=>x.id==='siyer-i-nebi-mehmed-ziya'&&x.editionYears?.includes(1924)));
assert.ok(siyer.sourceGate?.fallbackCandidates?.some(x=>x.id==='yorukan-peygamberimiz-1926'&&x.editionYears?.includes(1926)));
assert.ok((siyer.sourceGate?.reject||[]).some(x=>/academic thesis/i.test(x)));
assert.ok((siyer.sourceGate?.reject||[]).some(x=>/modern transliteration|simplification/i.test(x)));
assert.ok(siyer.sourceGate?.knownRejectedSources?.some(x=>/Diyanet 2015 Hâtemü’l-Enbiyâ/i.test(x.label)&&/© Diyanet|modern tashih/i.test(x.reason)));
assert.ok(siyer.sourceGate?.knownRejectedSources?.some(x=>/KSÜ SAMER/i.test(x.label)&&/sadeleştirme/i.test(x.reason)));
assert.ok(siyer.sourceGate?.knownRejectedSources?.some(x=>/Wikilala/i.test(x.label)&&/ticari yeniden kullanım/i.test(x.reason)));

console.log('siyer-source-gate: preferred Akseki historical source gate passed');

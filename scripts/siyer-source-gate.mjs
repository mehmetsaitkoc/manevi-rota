import assert from 'node:assert/strict';
import {starterBook} from '../src/library-catalog.mjs';

const siyer=starterBook('peygamberimiz-muhammed');
assert.ok(siyer,'selected level-three siyer target must exist');
assert.equal(siyer.stage,'level-3');
assert.equal(siyer.availability,'source-verified');
assert.equal(Boolean(siyer.asset),false,'pending siyer must stay unreadable until a reusable historical scan is approved');
assert.match(siyer.title,/Asr-ı Saâdet/);
assert.match(siyer.author,/Şiblî/);
assert.equal(siyer.translator,'Ömer Rıza Doğrul');
assert.equal(siyer.originalYear,1928);
assert.equal(siyer.authorDeathYear,1953);
assert.equal(siyer.sourceGate?.status,'selected-waiting-reusable-historical-scan');
assert.equal(siyer.sourceGate?.selectedWorkId,'asri-saadet-siyret');
assert.deepEqual(siyer.sourceGate?.acceptedEditionYears,[1928]);
assert.equal(siyer.sourceGate?.preferredScript,'ottoman-turkish');
assert.match(siyer.sourceGate?.selectionReason||'',/ciddi tahlil|tenkid/i);
assert.equal(siyer.sourceGate?.contentQualityGate?.status,'selected');
assert.equal(siyer.sourceGate?.contentQualityGate?.approvalRequiredBeforeReady,false);
assert.match(siyer.sourceGate?.contentQualityGate?.decision||'',/Asr-ı Saâdet/);
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.institution==='Wikilala'&&x.productionAllowed===false&&/commercial-reuse-prohibited/.test(x.access||'')));
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.institution==='Sakarya Üniversitesi Mehmet Uzun (Baboğlu) Koleksiyonu'&&x.inventory==='0104734'));
assert.ok(siyer.sourceGate?.catalogRecords?.some(x=>x.institution==='Uludağ Üniversitesi İlahiyat Fakültesi Kütüphanesi'&&x.inventory==='56411/56412'));
assert.ok(siyer.sourceGate?.alternateCandidates?.some(x=>x.id==='akseki-peygamberimiz-1934'&&x.status==='not-selected'));
assert.ok(siyer.sourceGate?.alternateCandidates?.some(x=>x.id==='siyer-i-nebi-mehmed-ziya'&&x.status==='fallback'));
assert.ok((siyer.sourceGate?.reject||[]).some(x=>/Wikilala full text/i.test(x)));
assert.ok((siyer.sourceGate?.reject||[]).some(x=>/modern transliteration|simplification/i.test(x)));
assert.ok(siyer.sourceGate?.knownRejectedSources?.some(x=>/Wikilala 1928 Asr-ı Saâdet/i.test(x.label)&&/ticari kullanım/i.test(x.reason)));

console.log('siyer-source-gate: definitive Asr-i Saadet source gate passed');
